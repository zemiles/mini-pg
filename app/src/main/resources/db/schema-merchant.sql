-- ---------------------------------------------------------------------
-- 5. 가맹점
-- ---------------------------------------------------------------------
CREATE TABLE merchant (
                          id            NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
                          merchant_id   VARCHAR2(20)        NOT NULL,
                          name          VARCHAR2(100 CHAR)  NOT NULL,
                          status        VARCHAR2(20)        NOT NULL,
                          created_at    TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                          updated_at    TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                          CONSTRAINT pk_merchant PRIMARY KEY (id),
                          CONSTRAINT uk_merchant_merchant_id UNIQUE (merchant_id),
                          CONSTRAINT ck_merchant_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'TERMINATED'))
);

COMMENT ON TABLE  merchant             IS '가맹점';
COMMENT ON COLUMN merchant.merchant_id IS '가맹점 ID (업무 키). 다른 테이블의 merchant_id가 가리키는 값';
COMMENT ON COLUMN merchant.status      IS 'ACTIVE(사용), SUSPENDED(정지), TERMINATED(해지)';


-- ---------------------------------------------------------------------
-- 6. 가맹점 시크릿 키
--    키 원문은 저장하지 않고 SHA-256 해시만 저장한다.
--    한 가맹점에 키를 여러 개 둘 수 있어서, 새 키 발급 → 옛 키 폐기로 교체할 수 있다.
-- ---------------------------------------------------------------------
CREATE TABLE merchant_secret_key (
                                     id            NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                     merchant_id   VARCHAR2(20)        NOT NULL,
                                     key_prefix    VARCHAR2(20)        NOT NULL,
                                     key_hash      VARCHAR2(64)        NOT NULL,
                                     environment   VARCHAR2(10)        NOT NULL,
                                     status        VARCHAR2(20)        NOT NULL,
                                     issued_at     TIMESTAMP           NOT NULL,
                                     revoked_at    TIMESTAMP,
                                     created_at    TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                                     updated_at    TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                                     CONSTRAINT pk_merchant_secret_key PRIMARY KEY (id),
                                     CONSTRAINT uk_secret_key_hash UNIQUE (key_hash),
                                     CONSTRAINT ck_secret_key_env CHECK (environment IN ('TEST', 'LIVE')),
                                     CONSTRAINT ck_secret_key_status CHECK (status IN ('ACTIVE', 'REVOKED')),
                                     CONSTRAINT fk_secret_key_merchant FOREIGN KEY (merchant_id) REFERENCES merchant (merchant_id)
);

-- 인증할 때: 가맹점 ID로 사용 중인 키를 찾음
CREATE INDEX ix_secret_key_merchant ON merchant_secret_key (merchant_id, status);

COMMENT ON TABLE  merchant_secret_key            IS '가맹점 시크릿 키. Basic 인증(가맹점ID:시크릿키)에 사용';
COMMENT ON COLUMN merchant_secret_key.key_prefix IS '키 앞부분 (예: test_sk_mini). 화면 표시, 어떤 키인지 구분용';
COMMENT ON COLUMN merchant_secret_key.key_hash   IS '시크릿 키의 SHA-256 해시(16진수 64자). 원문은 저장하지 않음';
COMMENT ON COLUMN merchant_secret_key.environment IS 'TEST(테스트 키), LIVE(운영 키)';
COMMENT ON COLUMN merchant_secret_key.status     IS 'ACTIVE(사용), REVOKED(폐기)';
COMMENT ON COLUMN merchant_secret_key.issued_at  IS '발급 일시';
COMMENT ON COLUMN merchant_secret_key.revoked_at IS '폐기 일시';
