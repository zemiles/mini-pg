-- ---------------------------------------------------------------------
-- 1. 거래 로그: 들어온 요청 한 건당 한 행 (재전송 포함)
-- ---------------------------------------------------------------------
CREATE TABLE request_log (
                             id                    NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
                             merchant_id           VARCHAR2(20)        NOT NULL,
                             request_type          VARCHAR2(20)        NOT NULL,
                             idempotency_key       VARCHAR2(64),
                             transaction_no        VARCHAR2(50),
                             transaction_date      VARCHAR2(8),
                             payment_key           VARCHAR2(50),
                             amount                NUMBER(15),
                             request_body          CLOB,
                             operation_id          NUMBER(19),
                             response_http_status  NUMBER(3),
                             response_code         VARCHAR2(20),
                             response_message      VARCHAR2(200 CHAR),
                             requested_at          TIMESTAMP           NOT NULL,
                             responded_at          TIMESTAMP,
                             created_at            TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                             updated_at            TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                             CONSTRAINT pk_request_log PRIMARY KEY (id),
                             CONSTRAINT ck_request_log_type CHECK (request_type IN ('APPROVE', 'CANCEL'))
);

CREATE INDEX ix_request_log_idem ON request_log (merchant_id, idempotency_key);
CREATE INDEX ix_request_log_tx   ON request_log (merchant_id, transaction_no);

COMMENT ON TABLE  request_log                      IS '거래 로그: 가맹점 요청 원본 기록 (재전송 포함, 유니크 없음)';
COMMENT ON COLUMN request_log.request_type         IS '요청 유형 (APPROVE, CANCEL)';
COMMENT ON COLUMN request_log.idempotency_key      IS '헤더 Idempotency-Key 값. 빠진 요청도 남기려고 NULL 허용';
COMMENT ON COLUMN request_log.transaction_no       IS '가맹점 거래번호 (승인일 때)';
COMMENT ON COLUMN request_log.transaction_date     IS '가맹점 거래일자 yyyyMMdd (승인일 때)';
COMMENT ON COLUMN request_log.payment_key          IS '취소 대상 결제키 (취소일 때)';
COMMENT ON COLUMN request_log.request_body         IS '요청 원문. 빌키 등 민감값은 가려서 저장';
COMMENT ON COLUMN request_log.operation_id         IS '연결된 결제 처리 ID. 검증에서 걸러진 요청은 NULL';
COMMENT ON COLUMN request_log.response_http_status IS '가맹점에 준 HTTP 상태 (200, 409, 422 등)';
COMMENT ON COLUMN request_log.response_code        IS '가맹점에 준 응답 코드';
COMMENT ON COLUMN request_log.requested_at         IS '요청 수신 일시';
COMMENT ON COLUMN request_log.responded_at         IS '응답 일시';


-- ---------------------------------------------------------------------
-- 2. 결제 처리: 승인 또는 취소 작업 한 건당 한 행 (멱등 키 저장)
-- ---------------------------------------------------------------------
CREATE TABLE payment_operation (
                                   id                NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                   merchant_id       VARCHAR2(20)        NOT NULL,
                                   operation_type    VARCHAR2(20)        NOT NULL,
                                   idempotency_key   VARCHAR2(64)        NOT NULL,
                                   transaction_no    VARCHAR2(50),
                                   transaction_date  VARCHAR2(8),
                                   payment_id        NUMBER(19),
                                   amount            NUMBER(15)          NOT NULL,
                                   payment_method    VARCHAR2(20)        NOT NULL,
                                   status            VARCHAR2(20)        NOT NULL,
                                   card_request_no   VARCHAR2(50)        NOT NULL,
                                   approval_no       VARCHAR2(30),
                                   result_code       VARCHAR2(20),
                                   result_message    VARCHAR2(200 CHAR),
                                   started_at        TIMESTAMP           NOT NULL,
                                   completed_at      TIMESTAMP,
                                   created_at        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                                   updated_at        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                                   CONSTRAINT pk_payment_operation PRIMARY KEY (id),
    -- 유니크 1: 같은 작업의 재전송 판별
                                   CONSTRAINT uk_operation_idem UNIQUE (merchant_id, operation_type, idempotency_key),
                                   CONSTRAINT uk_operation_card_req UNIQUE (card_request_no),
                                   CONSTRAINT ck_operation_type CHECK (operation_type IN ('APPROVE', 'CANCEL')),
                                   CONSTRAINT ck_operation_status CHECK (status IN ('PROCESSING', 'SUCCEEDED', 'FAILED', 'UNKNOWN')),
                                   CONSTRAINT ck_operation_amount CHECK (amount > 0),
    -- 승인이면 거래번호와 거래일자가 있고 원결제는 없음 / 취소면 원결제가 있음
                                   CONSTRAINT ck_operation_target CHECK (
                                       (operation_type = 'APPROVE' AND transaction_no IS NOT NULL AND transaction_date IS NOT NULL AND payment_id IS NULL)
                                           OR
                                       (operation_type = 'CANCEL' AND payment_id IS NOT NULL)
                                       )
);

-- 유니크 2: 승인 행에만 거래번호 유니크 (취소 행은 CASE가 전부 NULL이 되어 인덱스에서 빠짐)
CREATE UNIQUE INDEX uk_operation_approve ON payment_operation (
                                                               CASE WHEN operation_type = 'APPROVE' THEN merchant_id END,
                                                               CASE WHEN operation_type = 'APPROVE' THEN transaction_no END,
                                                               CASE WHEN operation_type = 'APPROVE' THEN transaction_date END
    );

-- 취소할 때 진행 중 취소 확인, 성공한 취소 합계 계산
CREATE INDEX ix_operation_payment ON payment_operation (payment_id, operation_type, status);
-- 정리 배치: 오래된 PROCESSING, UNKNOWN 찾기
CREATE INDEX ix_operation_status  ON payment_operation (status, started_at);

COMMENT ON TABLE  payment_operation                 IS '결제 처리: 승인/취소 작업 한 건당 한 행. 멱등 키와 처리 상태 관리';
COMMENT ON COLUMN payment_operation.operation_type  IS '작업 유형 (APPROVE, CANCEL)';
COMMENT ON COLUMN payment_operation.idempotency_key IS '헤더 Idempotency-Key 값. 가맹점 ID + 작업 유형과 묶어 유니크';
COMMENT ON COLUMN payment_operation.transaction_no  IS '가맹점 거래번호 (승인만)';
COMMENT ON COLUMN payment_operation.transaction_date IS '가맹점 거래일자 yyyyMMdd (승인만)';
COMMENT ON COLUMN payment_operation.payment_id      IS '취소 대상 원결제 ID (취소만)';
COMMENT ON COLUMN payment_operation.amount          IS '요청 금액. 같은 키 재전송 때 비교';
COMMENT ON COLUMN payment_operation.status          IS 'PROCESSING, SUCCEEDED, FAILED, UNKNOWN(결과 모름)';
COMMENT ON COLUMN payment_operation.card_request_no IS '우리가 카드사에 보낸 요청번호. 결과 모름 재조회용';
COMMENT ON COLUMN payment_operation.approval_no     IS '카드사 승인번호';
COMMENT ON COLUMN payment_operation.result_code     IS '카드사 응답 코드';
COMMENT ON COLUMN payment_operation.result_message  IS '카드사 응답 메시지, 실패 사유';
COMMENT ON COLUMN payment_operation.started_at      IS '처리 시작 일시';
COMMENT ON COLUMN payment_operation.completed_at    IS '처리 완료 일시';


-- ---------------------------------------------------------------------
-- 3. 결제: 성공한 원결제 한 건당 한 행 (INSERT만)
-- ---------------------------------------------------------------------
CREATE TABLE payment (
                         id                NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
                         payment_key       VARCHAR2(50)        NOT NULL,
                         merchant_id       VARCHAR2(20)        NOT NULL,
                         transaction_no    VARCHAR2(50)        NOT NULL,
                         transaction_date  VARCHAR2(8)         NOT NULL,
                         operation_id      NUMBER(19)          NOT NULL,
                         amount            NUMBER(15)          NOT NULL,
                         payment_method    VARCHAR2(20)        NOT NULL,
                         approval_no       VARCHAR2(30)        NOT NULL,
                         approved_at       TIMESTAMP           NOT NULL,
                         created_at        TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                         CONSTRAINT pk_payment PRIMARY KEY (id),
                         CONSTRAINT uk_payment_key UNIQUE (payment_key),
                         CONSTRAINT uk_payment_operation UNIQUE (operation_id),
                         CONSTRAINT uk_payment_tx UNIQUE (merchant_id, transaction_no, transaction_date),
                         CONSTRAINT ck_payment_amount CHECK (amount > 0)
);

COMMENT ON TABLE  payment                  IS '결제: 성공한 원결제 한 건당 한 행 (대사 대상, INSERT만)';
COMMENT ON COLUMN payment.payment_key      IS '가맹점에 주는 결제키. 순번이 아닌 추측하기 어려운 값';
COMMENT ON COLUMN payment.operation_id     IS '이 결제를 만든 승인 작업 ID';
COMMENT ON COLUMN payment.amount           IS '승인 금액';
COMMENT ON COLUMN payment.approval_no      IS '카드사 승인번호';
COMMENT ON COLUMN payment.approved_at      IS '승인 일시';


